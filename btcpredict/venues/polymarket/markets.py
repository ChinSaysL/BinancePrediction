"""Polymarket market discovery + settlement for the `*-updown-5m` family.

WHY THIS REPLACES THE BINANCE PREDICTION VENUE (measured 2026-09-16)
-------------------------------------------------------------------
The two venues list the SAME market: `btc-updown-5m-<unix>` exists on both,
same 5-minute boundary, same `Up`/`Down` outcomes, same Chainlink BTC/USD
family. That is why the slug convention matched byte for byte.

They are NOT the same bet, and that is the whole reason for this module's
second half:

* Binance's wrapper resolves on the POINT price at round end vs `startPrice`
  (measured 09-15: `end_price` sits 0.02 bps from the instantaneous Binance
  close -- a snapshot, not a window).
* Polymarket, from the market's own description: *"resolve to Up if the
  time-weighted average price (TWAP) of Bitcoin, generated by Chainlink, of the
  time range specified in the title is greater than or equal to the price at
  the BEGINNING of that range"* -- `cryptoMarketConfig: btc-5m-twap-60`,
  `resolutionSource: data.chain.link/streams/btc-usd-twap-60s-streams`.

Measured over 48 settled rounds with both sides' winners: **43 agree, 5
disagree (10.4%)**. The differing rounds sit mostly near the strike (|end -
strike| = 1.02, 1.04, 2.07 bps against a p10 of 1.43 bps), which is what a
different settlement VALUE predicts -- but 2 of the 5 were 7.1 and 23.9 bps, so
the mechanism explains 3 of 5. Treat the remainder as OPEN; do not build on the
assumption that disagreement is purely a near-strike phenomenon.

The consequence for pricing is blunt: PM's terminal variable is
`TWAP(0..T) - S_0` with variance `sigma^2 * T/3`, against the point rule's
`sigma^2 * T` -- **1.73x less dispersed**. Every calibration cell in FINDINGS
was fitted on the point rule and is therefore invalid here. See
`btcpredict/venues/polymarket/pricing.py`.

API MECHANICS (all verified live, no auth needed for any of it)
--------------------------------------------------------------
    gamma-api.polymarket.com/markets?slug=<slug>             -> only the OPEN one
    gamma-api.polymarket.com/markets?slug=<slug>&closed=true -> the settled one

Two traps, both of which cost a run when this was written:

1. `outcomes` and `outcomePrices` are returned as JSON **STRINGS**
   (`'["Up","Down"]'`). Parse both with `json.loads` or the winner comes back
   None while looking like "unresolved".
2. urllib's default User-Agent is answered with HTTP 403. Send a browser one.

Markets are created roughly a day ahead (`startDate` = creation, `eventStartTime`
= the round's real start), so the next round is always discoverable before the
current one ends -- no roll race.
"""

from __future__ import annotations

import json
import time
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass

GAMMA = "https://gamma-api.polymarket.com"
CLOB = "https://clob.polymarket.com"

#: The venue closes the tab on you without this. Verified: 403 on urllib's
#: default, 200 with a browser agent.
_UA = {
    "User-Agent": ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                   "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"),
    "Accept": "application/json",
}

SERIES = "btc-updown-5m"
ROUND_S = 300

#: The settlement rule, recorded on every row so a later analysis never has to
#: re-derive which variable a fill was actually paid on.
RESOLUTION = "chainlink-twap-60s-vs-range-start"


def period_s(series: str = SERIES) -> int:
    """The round length in seconds, read from the family name itself.

    `btc-updown-5m` -> 300, `btc-updown-15m` -> 900. Read from the slug rather
    than configured, because the slug IS the contract: the boundary a round
    aligns to is what its name says, and a second copy of that number could
    drift from it and silently compute the wrong window.
    """
    tail = str(series).rsplit("-", 1)[-1].lower()
    if tail.endswith("m"):
        tail = tail[:-1]
    try:
        n = int(tail)
    except ValueError:
        return ROUND_S
    return n * 60 if n > 0 else ROUND_S


def jparse(x):
    """Polymarket double-encodes these. A string that will not parse is None."""
    if isinstance(x, str):
        try:
            return json.loads(x)
        except (ValueError, TypeError):
            return None
    return x


def boundary(ts: float | None = None, series: str = SERIES) -> int:
    """The boundary containing `ts`, as the unix seconds the slug uses.

    `series` matters: the three 5m families align to 300 s and the three 15m
    families to 900 s, so a single hard-coded period would put the 15m rounds
    on the wrong boundary and fetch a market that does not exist.
    """
    p = period_s(series)
    return int((ts if ts is not None else time.time()) // p) * p


def slug_for(ts: float, series: str = SERIES) -> str:
    return "%s-%d" % (series, boundary(ts, series))


@dataclass(frozen=True)
class PmRound:
    """One round, as the rest of the bot needs it.

    `strike` is deliberately NOT sourced from Polymarket: gamma carries no
    reference price, because the resolution source is the Chainlink stream
    itself. The Binance wrapper's `variantData.startPrice` is the same oracle
    family at the same boundary, so it is the cheap, already-harvested proxy --
    recorded with `strike_src` so the provenance is never guessed later.
    """

    slug: str
    start_ts: int
    condition_id: str
    up_token: str
    down_token: str
    tick: float
    min_order: float
    end_ms: int
    neg_risk: bool
    liquidity: float
    resolution: str = RESOLUTION

    @property
    def seconds_left(self) -> float:
        return (self.end_ms / 1000.0) - time.time()

    @property
    def series(self) -> str:
        """The family, from the slug itself (`btc-updown-5m`)."""
        return self.slug.rsplit("-", 1)[0]

    @property
    def period_s(self) -> int:
        """This round's length. 300 for a 5m family, 900 for a 15m one."""
        return period_s(self.series)

    def token(self, side: str) -> str:
        return self.up_token if side == "Up" else self.down_token


def _get(url: str, timeout: float = 20.0):
    req = urllib.request.Request(url, headers=_UA)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as fh:
            return json.loads(fh.read().decode())
    except (urllib.error.HTTPError, urllib.error.URLError, ValueError,
            OSError):
        return None


def _to_round(m: dict) -> PmRound | None:
    toks = jparse(m.get("clobTokenIds"))
    if not toks or len(toks) != 2:
        return None
    end = m.get("endDate")
    end_ms = 0
    if end:
        try:
            import datetime as _dt
            end_ms = int(_dt.datetime.fromisoformat(
                end.replace("Z", "+00:00")).timestamp() * 1000)
        except ValueError:
            end_ms = 0
    slug = m.get("slug") or ""
    try:
        start_ts = int(slug.rsplit("-", 1)[1])
    except (IndexError, ValueError):
        start_ts = 0
    return PmRound(
        slug=slug, start_ts=start_ts,
        condition_id=m.get("conditionId") or "",
        up_token=str(toks[0]), down_token=str(toks[1]),
        tick=float(m.get("orderPriceMinTickSize") or 0.01),
        min_order=float(m.get("orderMinSize") or 5),
        end_ms=end_ms,
        neg_risk=bool(m.get("negRisk")),
        liquidity=float(m.get("liquidityNum") or 0.0),
    )


def fetch_round(ts: float, series: str = SERIES) -> PmRound | None:
    """The OPEN market for the round containing `ts`, or None.

    A round that has already ended returns None here by design -- the venue
    stops listing it as open -- which is why settlement has its own call.
    """
    d = _get("%s/markets?slug=%s" % (GAMMA, slug_for(ts, series)))
    if not d:
        return None
    return _to_round(d[0])


def fetch_round_closed(ts: float, series: str = SERIES) -> PmRound | None:
    """The CLOSED market for the round containing `ts`, or None.

    Same view as `fetch_round` but with `closed=true`. A closed market still
    carries every field `_to_round` needs (conditionId, clobTokenIds, endDate),
    so it is a complete round -- which is what makes it usable as a fallback
    AFTER the bell.
    """
    d = _get("%s/markets?slug=%s&closed=true" % (GAMMA, slug_for(ts, series)))
    if not d:
        return None
    return _to_round(d[0])


def fetch_round_any(ts: float, series: str = SERIES) -> PmRound | None:
    """The round containing `ts`, open OR closed.

    `fetch_round` alone is not enough to SETTLE, and the failure is silent.
    Settlement always runs after the bell (end_ms + 5 s, and resolution lands
    ~58 s later), which is exactly when the venue has stopped listing the round
    as open -- so an uncached lookup returned None and the round could never be
    resolved. That path is only reachable when the round is missing from the
    feed's cache, which is the state after every restart: measured 2026-09-16,
    a round that ended two minutes before a restart stayed unresolvable for the
    life of the process.
    """
    return fetch_round(ts, series) or fetch_round_closed(ts, series)


def current_and_next(now: float | None = None,
                     series: str = SERIES) -> tuple[PmRound | None, PmRound | None]:
    """(this round, next round) for ONE family. Both exist ahead of time.

    Per-FAMILY, not global: the venue lists `btc/eth/bnb-updown-5m` and their
    15m siblings as separate markets, and the arms trade all six. A caller that
    only ever asked for the default series would silently discover BTC alone,
    which is what left four of the six traded families with no websocket book.
    """
    now = now if now is not None else time.time()
    p = period_s(series)
    return fetch_round(now, series), fetch_round(now + p, series)


def settled_winner(ts: float, series: str = SERIES) -> tuple[str | None, str]:
    """(winner, status) for the round containing `ts`, from the closed market.

    `status` is `umaResolutionStatus` -- "resolved" is the only value that may
    be treated as final. Anything else means the market has closed but the
    outcome is not yet written, and booking a fill against it would invent P&L.
    """
    d = _get("%s/markets?slug=%s&closed=true" % (GAMMA, slug_for(ts, series)))
    if not d:
        return None, "not_listed"
    m = d[0]
    status = str(m.get("umaResolutionStatus") or "")
    oc, op = jparse(m.get("outcomes")), jparse(m.get("outcomePrices"))
    if not oc or not op or len(oc) != len(op):
        return None, status or "no_outcomes"
    try:
        winner = oc[max(range(len(op)), key=lambda i: float(op[i]))]
        prices = [float(x) for x in op]
    except (TypeError, ValueError):
        return None, status or "unparsable_prices"
    # A market whose prices are not a clean 0/1 is not settled, whatever the
    # status string says.
    if max(prices) < 0.99:
        return None, status or "not_decided"
    return winner, status


def settled_winner_strict(ts: float, series: str = SERIES) -> str | None:
    w, st = settled_winner(ts, series)
    return w if st == "resolved" else None


