"""Is the cross arm's TRIGGER aligned with what Polymarket actually pays on?

THE FINDING THIS TESTS. Polymarket does not settle on the point price at the
bell. Its own description: resolve Up if `the TWAP of Bitcoin, generated by
Chainlink, of the time range in the title` >= the price at the START of the
range, with `twapLookbackSeconds: 60`. The cross arm fires on the SPOT crossing
the strike. Those are different variables, and they diverge most exactly where
the arm trades (tau 5-60 s):

    at tau seconds left, the settlement window [T-60, T] is
        (60 - tau) seconds ALREADY PRINTED   +   tau seconds still unknown
    forecast = ((60 - tau) * mean(spot over the printed part) + tau * spot) / 60

At tau = 60 the forecast IS the spot (no advantage). At tau = 20 it is 67%
determined, at tau = 5 it is 92% determined. So inside the arm's own window the
settlement variable is largely KNOWN, and a spot-crossing trigger is firing on
the variable that is about to be averaged away.

WHAT IS MEASURED (read-only, live DB, Polymarket era only -- the feed_provider
column, NOT the fills.mode labels, which also cover the old venue):
  1. both signals at the same tau on the same rounds: which one's chosen side
     actually wins, and at what price;
  2. the DISAGREEMENT cohort -- where the spot says one side and the TWAP says
     the other, who is right (this is the whole question);
  3. the arm-shaped version: enter on the first tick the TWAP FORECAST crosses
     the strike, at the ask, one entry per round, with the 4-check battery.

Usage (on the VPS, analysis venv -- the bot venv has no numpy):
    /root/analysis-venv/bin/python tools/pm_twap_trigger_check.py
    /root/analysis-venv/bin/python tools/pm_twap_trigger_check.py --by-family
    /root/analysis-venv/bin/python tools/pm_twap_trigger_check.py --family bnb

`--by-family` exists because the arm trades NINE families and every one of its
knobs is per family (`cross_knob(MARKETS[i][0])`), so a pooled table cannot
answer "does this hold for the other coins". Read the COUNT first: the pooled
tau[5,60] entries split six ways is ~26 each, and `report` says `(thin)` under 8.
"""
from __future__ import annotations

import argparse
import collections
import math
import sqlite3
import sys

import numpy as np
import pandas as pd

DB = "/root/BinancePrediction/data/btcpredict.db"
PM_PROVIDER_LIKE = "chainlink-twap%"
LOOKBACK = 60.0          # twapLookbackSeconds from the venue's cryptoMarketConfig
FEE = lambda p: 0.07 * p * (1 - p)


def family_of(slug: str) -> str:
    """`bnb-updown-5m-1789680600` -> `bnb-updown-5m`, the knob's own key."""
    return str(slug).rsplit("-", 1)[0]


def load(db: str = DB) -> pd.DataFrame:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    q = pd.read_sql_query("""
      select q.slug, q.ts_ms, q.tau_s, q.spot, q.up_ask, q.down_ask
      from quotes q
      where q.spot is not null and q.ts_ms is not null
      order by q.slug, q.ts_ms
    """, con)
    r = pd.read_sql_query("""
      select slug, start_ms, end_ms, strike, winner, feed_provider
      from rounds
      where strike is not null and winner is not null
    """, con)
    con.close()
    r = r[r.feed_provider.fillna("").str.contains("twap", case=False)]
    r = r[r.slug.str.contains("-5m-")]
    return q.merge(r, on="slug", how="inner").sort_values(["slug", "ts_ms"])


def per_round(df: pd.DataFrame, taus: list[float]) -> pd.DataFrame:
    """One row per (round, tau): spot signal, TWAP-forecast signal, prices."""
    out = []
    for slug, g in df.groupby("slug", sort=False):
        g = g.sort_values("ts_ms")
        ts = g.ts_ms.to_numpy(dtype=float)
        sp = g.spot.to_numpy(dtype=float)
        tau = g.tau_s.to_numpy(dtype=float)
        strike = float(g.strike.iloc[0])
        winner = g.winner.iloc[0]
        if not np.isfinite(strike) or strike <= 0:
            continue
        for t in taus:
            i = int(np.argmin(np.abs(tau - t)))
            if abs(tau[i] - t) > max(1.2, 0.1 * t):
                continue
            # the printed part of the settlement window: [now-60, now]
            lo = ts[i] - LOOKBACK * 1000.0
            m = (ts >= lo) & (ts <= ts[i]) & np.isfinite(sp)
            known_len = min(LOOKBACK, max(0.0, (ts[i] - lo) / 1000.0))
            mean_known = float(np.mean(sp[m])) if m.sum() else float(sp[i])
            if tau[i] >= LOOKBACK:            # nothing printed yet
                fc = float(sp[i])
            else:
                fc = ((LOOKBACK - tau[i]) * mean_known + tau[i] * float(sp[i])) / LOOKBACK
            d_spot = 1e4 * (float(sp[i]) - strike) / strike
            d_fc = 1e4 * (fc - strike) / strike
            up_ask = float(g.up_ask.iloc[i]) if np.isfinite(g.up_ask.iloc[i]) else np.nan
            dn_ask = float(g.down_ask.iloc[i]) if np.isfinite(g.down_ask.iloc[i]) else np.nan
            out.append(dict(slug=slug, tau=float(tau[i]), grid=float(t), d_spot=d_spot,
                            d_fc=d_fc,
                            spot=float(sp[i]), fc=fc, strike=strike, winner=winner,
                            up_ask=up_ask, dn_ask=dn_ask, ts_ms=float(ts[i]),
                            known_frac=min(1.0, ((LOOKBACK - tau[i]) / LOOKBACK)
                                           if tau[i] < LOOKBACK else 0.0)))
    return pd.DataFrame(out)


def stats(sub: pd.DataFrame, label: str, col: str) -> None:
    """Score `col` as a directional signal: side = Up if col > 0 else Down."""
    s = sub.dropna(subset=[col, "up_ask", "dn_ask"]).copy()
    s = s[(s.up_ask > 0.001) & (s.dn_ask > 0.001)]
    if len(s) < 8:
        print(f"      {label:<18} n={len(s)} (thin)")
        return
    side_up = s[col] > 0
    ask = np.where(side_up, s.up_ask, s.dn_ask)
    won = np.where(side_up, s.winner == "Up", s.winner == "Down")
    per = won - ask - np.array([FEE(a) for a in ask])
    print(f"      {label:<18} n={len(s):4d} agree={((s.d_spot>0)==(s.d_fc>0)).mean():5.1%} "
          f"win={won.mean():6.1%} ask={ask.mean():.3f} per-share={per.mean():+.4f} "
          f"t={per.mean() / (per.std() / math.sqrt(len(per))):+.2f}")


def parse_args():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("db", nargs="?", default=DB, help="path to btcpredict.db")
    ap.add_argument("--family", default=None,
                    help="slug prefix to keep, e.g. bnb or bnb-updown-5m")
    ap.add_argument("--by-family", action="store_true",
                    help="add the per-family arm-shaped split")
    return ap.parse_args()


def main() -> None:
    args = parse_args()
    df = load(args.db)
    if args.family:
        df = df[df.slug.str.startswith(args.family)]
    if df.empty:
        print("no Polymarket-era rounds with spot + strike + winner yet"); return
    days = pd.to_datetime(df.ts_ms, unit="ms", utc=True).dt.strftime("%m-%d")
    df["day"] = days
    print(f"Polymarket-era 5m rounds with spot+strike+winner: {df.slug.nunique()} "
          f"| quote rows {len(df)} | days {sorted(df.day.unique())}")

    taus = [1, 2, 3, 5, 10, 15, 20, 30, 45, 60, 90]
    pr = per_round(df, taus)
    if pr.empty:
        print("no usable (round, tau) rows"); return
    print(f"\n=== OUR RUNNING-60s-MEAN vs THE ASK, BY TIME LEFT ===")
    print("    the proposal: sample spot every 1 s, integrate the tail 60 s, and act before")
    print("    the oracle posts. win% is that forecast's accuracy; be% is what the ASK")
    print("    requires. Only the gap matters -- a certain winner at a certain price is zero.")
    print(f"{'tau':>4} {'n':>5} {'printed':>8} {'fcst win%':>10} {'ask':>7} "
          f"{'be%':>7} {'edge':>5} {'fcst/sh':>9} {'spot win%':>10} {'spot/sh':>9}")
    for t in taus:
        s = pr[pr.grid == t].dropna(subset=["up_ask", "dn_ask"])
        s = s[(s.up_ask > 0.001) & (s.dn_ask > 0.001)]
        if len(s) < 8:
            continue
        up = s.d_spot > 0
        ask = np.where(up, s.up_ask, s.dn_ask)
        won = np.where(up, s.winner == "Up", s.winner == "Down")
        per_sp = won - ask - np.array([FEE(a) for a in ask])
        upf = s.d_fc > 0
        askf = np.where(upf, s.up_ask, s.dn_ask)
        wonf = np.where(upf, s.winner == "Up", s.winner == "Down")
        per_fc = wonf - askf - np.array([FEE(a) for a in askf])
        dem = s.winner == "Up"
        be = askf + np.array([FEE(a) for a in askf])
        winf = wonf.mean()
        print(f"{t:>4.0f} {len(s):>5d} {s.known_frac.mean():>8.0%} {winf:>10.1%} "
              f"{askf.mean():>7.3f} {be.mean():>7.1%} "
              f"{'YES' if winf > be.mean() else 'no':>5} {per_fc.mean():>+9.4f} "
              f"{won.mean():>10.1%} {per_sp.mean():>+9.4f}")
    print("  printed = share of the settlement window already on the tape at that tau")
    print("  HIT = the signal's side matches the actual winner (this is a CALIBRATION "
          "measure, not money -- a side can be right and still be overpriced)")

    print(f"\n=== THE DISAGREEMENT COHORT, PRICED (spot says one side, TWAP the other) ===")
    print("    if the venue anchored on the visible spot, the forecast's side is cheap")
    dis = pr[(np.sign(pr.d_spot) != np.sign(pr.d_fc))
             & np.isfinite(pr.up_ask) & np.isfinite(pr.dn_ask)].copy()
    print(f"{'tau':>4} {'n':>4} {'side':>8} {'ask':>6} {'win%':>7} {'per-share':>10} "
          f"{'t':>6} {'day-t':>7} {'halves':>15}")
    for t in taus:
        s = dis[dis.grid == t]
        if len(s) < 8:
            continue
        for who in ("fcst", "spot"):
            up = (s.d_fc > 0) if who == "fcst" else (s.d_spot > 0)
            ask = np.where(up, s.up_ask, s.dn_ask)
            won = np.where(up, s.winner == "Up", s.winner == "Down")
            per = won - ask - np.array([FEE(a) for a in ask])
            n = len(per)
            tt = per.mean() / (per.std() / math.sqrt(n)) if per.std() else 0.0
            days = pd.to_datetime(s.ts_ms, unit="ms", utc=True).dt.strftime("%m-%d").to_numpy()
            dm = [per[days == d].mean() for d in np.unique(days)]
            td = (np.mean(dm) / (np.std(dm) / math.sqrt(len(dm)))) if np.std(dm) else 0.0
            h = n // 2
            print(f"{t:>4.0f} {n:>4d} {who:>8} {ask.mean():>6.3f} {won.mean():>7.1%} "
                  f"{per.mean():>+10.4f} {tt:>+6.2f} {td:>+7.2f} "
                  f"{per[:h].mean():>+7.4f}/{per[h:].mean():>+7.4f}")

    print(f"\n=== ARM-SHAPED HEAD-TO-HEAD (same rounds, same entry rule, one entry) ===")
    print("    enter on the FIRST tick the chosen signal crosses the strike")

    def arm(tau_lo: float, tau_hi: float, mode: str,
            data: pd.DataFrame | None = None) -> list[dict]:
        rows = []
        for slug, g in (df if data is None else data).groupby("slug", sort=False):
            g = g.sort_values("ts_ms")
            ts = g.ts_ms.to_numpy(dtype=float); sp = g.spot.to_numpy(dtype=float)
            tau = g.tau_s.to_numpy(dtype=float); strike = float(g.strike.iloc[0])
            winner = g.winner.iloc[0]
            if not np.isfinite(strike) or strike <= 0:
                continue
            prev = None
            for i in range(len(g)):
                if not (tau_lo <= tau[i] <= tau_hi):
                    continue
                if mode == "spot":
                    val = float(sp[i])
                else:
                    lo = ts[i] - LOOKBACK * 1000.0
                    m = (ts >= lo) & (ts <= ts[i]) & np.isfinite(sp)
                    mk = float(np.mean(sp[m])) if m.sum() else float(sp[i])
                    val = (float(sp[i]) if tau[i] >= LOOKBACK else
                           ((LOOKBACK - tau[i]) * mk + tau[i] * float(sp[i])) / LOOKBACK)
                sgn = 1 if val > strike else -1
                if prev is not None and sgn != prev:
                    side_up = sgn > 0
                    ask = float(g.up_ask.iloc[i] if side_up else g.down_ask.iloc[i])
                    if not (0.01 < ask < 0.99):
                        prev = sgn; continue
                    won = (winner == "Up") if side_up else (winner == "Down")
                    lo2 = ts[i] - LOOKBACK * 1000.0
                    m2 = (ts >= lo2) & (ts <= ts[i]) & np.isfinite(sp)
                    mk2 = float(np.mean(sp[m2])) if m2.sum() else float(sp[i])
                    fcv = (float(sp[i]) if tau[i] >= LOOKBACK else
                           ((LOOKBACK - tau[i]) * mk2 + tau[i] * float(sp[i])) / LOOKBACK)
                    rows.append(dict(slug=slug, family=family_of(slug),
                                     per=(1.0 if won else 0.0) - ask - FEE(ask),
                                     ask=ask, won=won, tau=tau[i], side_up=side_up,
                                     d_fc=1e4 * (fcv - strike) / strike,
                                     day=pd.to_datetime(ts[i], unit="ms",
                                                        utc=True).strftime("%m-%d")))
                    break
                prev = sgn
        return rows

    def report(rows: list[dict], label: str) -> None:
        if len(rows) < 8:
            print(f"    {label:<24} n={len(rows)} (thin)"); return
        d = pd.DataFrame(rows); v = d.per.to_numpy()
        n = len(v); m = v.mean(); t = m / (v.std() / math.sqrt(n)) if v.std() else 0.0
        dm = [v[d.day.values == x].mean() for x in d.day.unique()]
        td = (np.mean(dm) / (np.std(dm) / math.sqrt(len(dm)))) if np.std(dm) else 0.0
        h = n // 2
        print(f"    {label:<24} n={n:4d} ask={d.ask.mean():.3f} win={d.won.mean():5.1%} "
              f"per-share={m:+.4f} t={t:+.2f} day-t={td:+.2f} "
              f"halves={v[:h].mean():+.4f}/{v[h:].mean():+.4f} "
              f"days+={sum(1 for x in dm if x > 0)}/{len(dm)} tauMed={d.tau.median():.0f}s")

    for tau_lo, tau_hi in [(5, 60), (5, 120)]:
        print(f"  -- tau [{tau_lo},{tau_hi}] --")
        report(arm(tau_lo, tau_hi, "spot"), "SPOT cross (what ships)")
        report(arm(tau_lo, tau_hi, "fcst"), "TWAP-FCAST cross (the fix)")

    print(f"\n=== KEEP THE SPOT TRIGGER, FILTER ON THE VENUE'S STATISTIC ===")
    print("    at a spot entry, does the venue's own TWAP-forecast already point the")
    print("    SAME way? (if the venue's variable disagrees, the spot cross is noise)")
    for tau_lo, tau_hi in [(5, 60), (5, 120)]:
        rows = arm(tau_lo, tau_hi, "spot")
        if len(rows) < 12:
            print(f"    tau [{tau_lo},{tau_hi}] n={len(rows)} (thin)"); continue
        d = pd.DataFrame(rows)
        keep = d[(d.d_fc > 0) == d.side_up]
        drop = d[(d.d_fc > 0) != d.side_up]
        print(f"  -- tau [{tau_lo},{tau_hi}] --")
        report(keep.to_dict("records"), "FORECAST AGREES (keep)")
        report(drop.to_dict("records"), "FORECAST DISAGREES (drop)")
        print(f"     -> drop the disagree cohort: n {len(d)} -> {len(keep)}, "
              f"total per-share {d.per.sum():+.2f} -> {keep.per.sum():+.2f}")

    print(f"\n=== THE PRICE OF A DISTANCE FLOOR (|venue statistic - strike| at entry) ===")
    print("    Binance and Chainlink disagree inside ~2 bps. One cent on BTC is 1.3 bps.")
    print("    A round decided inside that band is uncallable, whatever the trigger says.")
    d0 = pd.DataFrame(arm(5, 60, "spot"))
    d0["abs_fc_bps"] = d0.d_fc.abs()
    edges = [0.0, 1.0, 2.0, 3.0, 5.0, 8.0, 1e9]
    print(f"  -- spot-cross entries, tau [5,60], n={len(d0)} --")
    for a, b in zip(edges, edges[1:]):
        s = d0[(d0.abs_fc_bps >= a) & (d0.abs_fc_bps < b)]
        hi = f"{b:>4.0f}" if b < 1e9 else "  + "
        if len(s) < 5:
            print(f"     |fc-K| {a:>4.0f}-{hi} bps  n={len(s):3d} (thin)")
            continue
        print(f"     |fc-K| {a:>4.0f}-{hi} bps  n={len(s):3d} ask={s.ask.mean():.3f} "
              f"win={s.won.mean():5.1%} per-share={s.per.mean():+.4f} "
              f"total={s.per.sum():+.2f}")
    print("  -- cumulative floor --")
    for D in (0.0, 1.0, 2.0, 3.0, 5.0, 8.0):
        s = d0[d0.abs_fc_bps >= D]
        if len(s) < 8:
            continue
        print(f"     drop |fc-K| < {D:>3.0f} bps: n={len(s):3d} "
              f"per-share={s.per.mean():+.4f} total={s.per.sum():+.2f} "
              f"(dropped {len(d0) - len(s)})")

    # ⭐ THE FLOOR THAT MATTERS ONCE THE TRIGGER IS THE FORECAST: the FC entry's
    # OWN margin, not the spot entry's. The live fires of 2026-09-17/18 show the
    # shape to test -- three of four sat at |fc-level| = 0.00 bps (the value
    # prints equal to the level) and all three lost, while the only winner sat
    # at 2.0 bps. A first-touch trigger is ALWAYS at zero margin by
    # construction, so if the zero bucket is the weak one, every fc entry is the
    # weak entry. Halves and day-t are printed because a floor is a PARAMETER:
    # this repo ships a direction only when it ranks the same in both halves.
    print(f"\n=== THE FC ENTRY'S OWN MARGIN (|fc - K| at the fire) ===")
    fc_rows = pd.DataFrame(arm(5, 60, "fcst"))
    if len(fc_rows) < 12:
        print(f"    n={len(fc_rows)} (thin)")
    else:
        fc_rows["abs_fc_bps"] = fc_rows.d_fc.abs()
        print(f"  -- fc-cross entries, tau [5,60], n={len(fc_rows)} --")
        for a, b in zip(edges, edges[1:]):
            s = fc_rows[(fc_rows.abs_fc_bps >= a) & (fc_rows.abs_fc_bps < b)]
            hi = f"{b:>4.0f}" if b < 1e9 else "  + "
            if len(s) < 5:
                print(f"     |fc-K| {a:>4.0f}-{hi} bps  n={len(s):3d} (thin)")
                continue
            v = s.per.to_numpy()
            h = len(v) // 2
            print(f"     |fc-K| {a:>4.0f}-{hi} bps  n={len(s):3d} "
                  f"ask={s.ask.mean():.3f} win={s.won.mean():5.1%} "
                  f"per-share={s.per.mean():+.4f} "
                  f"halves={v[:h].mean():+.4f}/{v[h:].mean():+.4f}")
        print("  -- cumulative floor on the fc entry's own margin --")
        for D in (0.0, 0.5, 1.0, 2.0, 3.0, 5.0):
            s = fc_rows[fc_rows.abs_fc_bps >= D]
            if len(s) < 8:
                print(f"     drop < {D:>3.1f} bps: n={len(s):3d} (thin)")
                continue
            v = s.per.to_numpy()
            h = len(v) // 2
            print(f"     drop < {D:>3.1f} bps: n={len(s):3d} "
                  f"per-share={s.per.mean():+.4f} total={s.per.sum():+.2f} "
                  f"halves={v[:h].mean():+.4f}/{v[h:].mean():+.4f} "
                  f"(dropped {len(fc_rows) - len(s)})")

    # THE TEST: rounds where the two rules pick OPPOSITE sides.
    spm = {r["slug"]: r for r in arm(5, 60, "spot")}
    dis = [r for r in arm(5, 60, "fcst")
           if r["slug"] in spm and r["side_up"] != spm[r["slug"]]["side_up"]]
    print(f"\n=== WHERE THE TWO RULES DISAGREE (tau 5-60): who is right? ===")
    if len(dis) >= 5:
        d = pd.DataFrame(dis)
        sp_ask = np.array([spm[s]["ask"] for s in d.slug])
        sp_won = np.array([spm[s]["won"] for s in d.slug])
        print(f"    n={len(d)}")
        print(f"    TWAP-FCAST side wins {d.won.mean():5.1%} at ask {d.ask.mean():.3f} "
              f"-> per-share {d.per.mean():+.4f}")
        print(f"    SPOT       side wins {sp_won.mean():5.1%} at ask {sp_ask.mean():.3f} "
              f"-> per-share {np.mean(sp_won - sp_ask - FEE(sp_ask)):+.4f}")
        print(f"    the two sides are opposite, so the two win rates sum to ~100%: "
              f"the rule that sums ABOVE 100% is the one the venue pays on")
    else:
        print(f"    n={len(dis)} (thin -- the two rules almost always agree)")


    # THE SPLIT A POOLED TABLE CANNOT ANSWER. Every cross knob is per FAMILY, so
    # "does the forecast trigger hold for the other coins" is a per-family
    # question. Read the COUNT first: these are the pooled entries split six
    # ways, and `report` prints `(thin)` below n=8 rather than dressing up four
    # rounds as a result. A family that is thin is not evidence either way.
    if args.by_family:
        print(f"\n=== ARM-SHAPED BY FAMILY (tau 5-60, one entry per round) ===")
        print(f"    {len(df.slug.unique())} rounds, "
              f"days {sorted(df.day.unique())} | `(thin)` = n < 8")
        for fam in sorted({family_of(s) for s in df.slug.unique()}):
            sub = df[df.slug.map(family_of) == fam]
            for mode, label in (("spot", "SPOT"), ("fcst", "FC  ")):
                report(arm(5, 60, mode, sub), f"{fam:<20} {label}")


if __name__ == "__main__":
    main()
